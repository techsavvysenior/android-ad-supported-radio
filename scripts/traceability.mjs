#!/usr/bin/env node
// Builds docs/traceability.md: which Kotlin tests cover which use case. A test covers every UC id
// in its name. `--check` fails when an automated use case has no test, a test names an unknown
// use case, or the committed matrix is out of date. `--write` regenerates it. Node 22, no dependencies.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const read = (p) => readFileSync(join(root, p), 'utf8');

const useCases = [...read('docs/use-cases.md').matchAll(/^\| (UC-\d\d) \| (.+?) \| (automated|manual) \|$/gm)]
  .map(([, id, title, mode]) => ({ id, title, mode }));

function files(dir) {
  const out = [];
  for (const name of readdirSync(join(root, dir))) {
    const p = join(dir, name);
    if (name === 'build' || name.startsWith('.')) continue;
    if (statSync(join(root, p)).isDirectory()) out.push(...files(p));
    else if (p.endsWith('.kt') && p.includes('/src/test/')) out.push(p);
  }
  return out;
}

const coverage = Object.fromEntries(useCases.map((u) => [u.id, []]));
const unknown = [];
for (const file of [...files('core'), ...files('app')]) {
  for (const [, name] of read(file).matchAll(/fun `([^`]+)`/g)) {
    for (const [id] of name.matchAll(/UC-\d\d/g)) {
      if (coverage[id]) coverage[id].push(`${name} (${file.split('/').pop()})`);
      else unknown.push(`${id} in ${relative(root, join(root, file))}`);
    }
  }
}

const missing = useCases.filter((u) => u.mode === 'automated' && coverage[u.id].length === 0).map((u) => u.id);

const lines = [
  '# Traceability matrix',
  '',
  'Generated by `node scripts/traceability.mjs --write`. Do not edit by hand.',
  '',
  '| Use case | Tests | Verified |',
  '|---|---:|---|',
  ...useCases.map((u) => `| ${u.id} ${u.title} | ${coverage[u.id].length} | ${u.mode === 'manual' ? 'manual, see test plan' : 'automated'} |`),
  '',
  '## Tests by use case',
  '',
];
for (const u of useCases) {
  lines.push(`### ${u.id} ${u.title}`, '');
  if (coverage[u.id].length === 0) lines.push(u.mode === 'manual' ? '- Manual check in [test-plan.md](test-plan.md)' : '- **No test**');
  else lines.push(...coverage[u.id].map((t) => `- ${t}`));
  lines.push('');
}
const matrix = lines.join('\n');

if (process.argv.includes('--write')) writeFileSync(join(root, 'docs/traceability.md'), matrix);

let failed = false;
if (missing.length) { console.error(`Automated use cases with no test: ${missing.join(', ')}`); failed = true; }
if (unknown.length) { console.error(`Tests name unknown use cases:\n  ${unknown.join('\n  ')}`); failed = true; }
if (process.argv.includes('--check') && read('docs/traceability.md') !== matrix) {
  console.error('docs/traceability.md is out of date. Run: node scripts/traceability.mjs --write');
  failed = true;
}
const tests = Object.values(coverage).reduce((n, list) => n + list.length, 0);
console.log(`${useCases.length} use cases, ${tests} test links, ${missing.length} automated without a test.`);
process.exit(failed ? 1 : 0);
